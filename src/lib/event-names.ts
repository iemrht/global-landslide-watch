export type EventNameKind = 'verified-name' | 'official-title' | 'official-location' | 'source-text-warning';
type NamedEvent = {id: string; geometry?: {coordinates: number[]}; properties: {place: string; time: number; ids?: string; originalPlace?: string; eventAliases?: string; eventNameSourceUrl?: string; eventNameKind?: EventNameKind}};
export function applyVerifiedEventName<T extends NamedEvent>(event: T): T {
  const ids = [event.id, ...(event.properties.ids?.split(',').filter(Boolean) ?? [])];
  const day = Number.isFinite(event.properties.time) ? new Date(event.properties.time).toISOString().slice(0,10) : '';
  const entry = ids.map(id => verifiedNames[id]).find(item => item && item.day === day);
  const raw = event.properties.originalPlace ?? event.properties.place;
  const properties = {...event.properties, eventNameSourceUrl: 'https://earthquake.usgs.gov/earthquakes/eventpage/' + encodeURIComponent(event.id)};
  if (entry) return {...event, properties: {...properties, originalPlace: raw, place: entry.name,
    eventAliases: entry.aliases, eventNameSourceUrl: entry.source, eventNameKind: 'verified-name'}};
  if (!raw || /[?�<>]/u.test(raw)) {
    const coords=event.geometry?.coordinates;
    const country=raw?.split(',').at(-1)?.trim();
    const region=country && !/[?�<>]/u.test(country) ? country + ' · ' : '';
    const location=coords?.slice(0,2).every(Number.isFinite)
      ? region + '震中 ' + Math.abs(coords[1]).toFixed(3) + '°' + (coords[1]>=0?'N':'S') + ', ' + Math.abs(coords[0]).toFixed(3) + '°' + (coords[0]>=0?'E':'W')
      : '地名待核实 · ' + event.id;
    return {...event, properties: {...properties, originalPlace: raw, place: location, eventNameKind: 'source-text-warning'}};
  }
  return {...event, properties: {...properties, place: raw, eventNameKind: /\b(?:earthquake|aftershock)\b/i.test(raw) ? 'official-title' : 'official-location'}};
}
export function eventNameLabel(kind?: EventNameKind) {
  return kind === 'verified-name' ? '已核实事件名' : kind === 'official-title' ? 'USGS 目录事件名'
    : kind === 'source-text-warning' ? '源地名字符异常，以震中定位' : '官方位置描述（非事件专名）';
}
